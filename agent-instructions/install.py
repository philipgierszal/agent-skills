#!/usr/bin/env python3
"""Install the shared agent working rules and this repository's skills for Claude Code and Codex.

- Writes `working-rules.md` into ~/.claude/CLAUDE.md and ~/.codex/AGENTS.md, between markers. Text outside the
  markers (your own or a project's instructions) is kept; running it again replaces only the marked block.
- Links every `skills/<name>` into ~/.claude/skills and ~/.codex/skills (a junction on Windows, a symlink elsewhere),
  so the installed skills follow this checkout.

Usage: python agent-instructions/install.py [--dry-run]
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
START = "<!-- agent-instructions:start (generated by agent-skills/agent-instructions/install.py; edit there) -->"
END = "<!-- agent-instructions:end -->"
TARGETS = [Path.home() / ".claude" / "CLAUDE.md", Path.home() / ".codex" / "AGENTS.md"]
SKILL_DIRS = [Path.home() / ".claude" / "skills", Path.home() / ".codex" / "skills"]


def with_block(text: str, block: str) -> str:
    """Return text with the marked block replaced, or appended when absent."""
    wrapped = f"{START}\n{block.strip()}\n{END}\n"
    if START in text and END in text:
        head, rest = text.split(START, 1)
        tail = rest.split(END, 1)[1]
        return head + wrapped + tail.lstrip("\n")
    return (text.rstrip() + "\n\n" if text.strip() else "") + wrapped


def link(target: Path, source: Path, dry: bool) -> str:
    if target.exists() or target.is_symlink():
        return f"kept {target}"
    if dry:
        return f"would link {target} -> {source}"
    target.parent.mkdir(parents=True, exist_ok=True)
    if os.name == "nt":
        subprocess.run(["cmd", "/c", "mklink", "/J", str(target), str(source)], check=True, capture_output=True)
    else:
        target.symlink_to(source, target_is_directory=True)
    return f"linked {target}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    block = (HERE / "working-rules.md").read_text(encoding="utf-8")
    for target in TARGETS:
        old = target.read_text(encoding="utf-8") if target.exists() else ""
        new = with_block(old, block)
        if new != old and not args.dry_run:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(new, encoding="utf-8")
        print(("would update " if args.dry_run else "updated ") + str(target) if new != old else f"unchanged {target}")
    for skill in sorted(p for p in (REPO / "skills").iterdir() if (p / "SKILL.md").exists()):
        for base in SKILL_DIRS:
            print(link(base / skill.name, skill, args.dry_run))
    return 0


if __name__ == "__main__":
    sys.exit(main())
